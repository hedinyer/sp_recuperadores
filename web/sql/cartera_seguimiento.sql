-- Acceso desde la app (mismo patrón permisivo que placas/recuperadores).
alter table public.cartera_perfiles enable row level security;
alter table public.cartera_casos enable row level security;
alter table public.cartera_gestiones enable row level security;

drop policy if exists "cartera_perfiles_all" on public.cartera_perfiles;
create policy "cartera_perfiles_all"
  on public.cartera_perfiles for all
  using (true) with check (true);

drop policy if exists "cartera_casos_all" on public.cartera_casos;
create policy "cartera_casos_all"
  on public.cartera_casos for all
  using (true) with check (true);

drop policy if exists "cartera_gestiones_all" on public.cartera_gestiones;
create policy "cartera_gestiones_all"
  on public.cartera_gestiones for all
  using (true) with check (true);

grant select, insert, update, delete on public.cartera_perfiles to anon, authenticated;
grant select, insert, update, delete on public.cartera_casos to anon, authenticated;
grant select, insert, update, delete on public.cartera_gestiones to anon, authenticated;
grant usage, select on sequence public.cartera_gestiones_id_seq to anon, authenticated;
