-- Seguimiento de cartera (proyecto Supabase actual de la app).
-- Aplicar en el SQL Editor del proyecto hvtbzxifzkbvmqpshmqw.

create table if not exists public.cartera_perfiles (
  id text primary key,
  nombre text not null,
  activo boolean not null default true
);

create table if not exists public.cartera_casos (
  placa text primary key,
  perfil_id text references public.cartera_perfiles (id) on delete set null,
  categoria text,
  status text not null default 'pendiente'
    check (
      status = any (
        array[
          'pendiente',
          'contactado',
          'compromiso',
          'abono',
          'no_contesta',
          'visita',
          'en_ruta',
          'recuperada',
          'cerrado'
        ]
      )
    ),
  notas text,
  updated_at timestamptz not null default now()
);

create table if not exists public.cartera_gestiones (
  id bigint generated by default as identity primary key,
  placa text not null,
  perfil_id text not null references public.cartera_perfiles (id),
  status text not null,
  categoria text,
  notas text,
  monto bigint,
  created_at timestamptz not null default now()
);

create index if not exists cartera_gestiones_placa_created_idx
  on public.cartera_gestiones (placa, created_at desc);

